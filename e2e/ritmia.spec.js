import { expect, test } from '@playwright/test'
async function selectPreset(page, id) {
  await page.getByRole('combobox', { name: 'Preset', exact: true }).click()
  await page.locator(`[role="option"][data-preset-id="${id}"]`).click()
}
const presets = [ ['bulerias', 12, [0, 3, 6, 8, 10]], ['bulerias-7', 12, [0, 3, 7, 8, 10]], ['tangos', 4, [1, 3]], ['marcato', 4, [0, 1, 2, 3]] ]
for (const [id, count, strong] of presets) {
  test(`${id}: preset lock and free editing preserve levels, B and marker`, async ({ page }) => {
    const errors = []; page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await page.getByRole('button', { name: 'Nivel 2 — Dos ritmos' }).click()
    await page.getByLabel('Numerador compás B', { exact: true }).fill('9')
    await selectPreset(page, id)
    const keys = page.getByRole('group', { name: 'Secuenciador pista A' }).getByRole('button')
    await expect(keys).toHaveCount(count)
    const accents = await keys.evaluateAll(els => els.map(el => Number(el.dataset.accent)))
    expect(accents.flatMap((a, i) => a === 2 ? [i] : [])).toEqual(strong)
    if (id.startsWith('bulerias')) {
      await expect(keys.first()).toHaveAccessibleName('Pulso 12, acento: fuerte')
      await expect(keys.nth(11)).toHaveAccessibleName(/Pulso 11/)
    }
    await expect(page.getByLabel('Numerador compás B', { exact: true })).toHaveValue('9')
    await expect(page.getByLabel('Marcar inicio de compás').filter({ visible: true })).not.toBeChecked()
    await expect(keys.first()).toBeDisabled()
    await page.getByRole('button', { name: 'Nivel 1 — Ritmo' }).click()
    await expect(keys).toHaveCount(count)
    await page.getByRole('button', { name: 'Nivel 2 — Dos ritmos' }).click()
    await expect(keys.first()).toBeDisabled()
    await selectPreset(page, '')
    await expect(keys.first()).toBeEnabled()
    await keys.first().click()
    await expect(keys.first()).toHaveAttribute('data-accent', String((accents[0] + 1) % 3))
    expect(errors).toEqual([])
  })
}

test('transport rapid toggles, running reset and meter changes retain a single audio timeline', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Reproducir', exact: true }).click()
  await selectPreset(page, 'marcato')
  await expect(page.getByRole('button', { name: 'Detener reproducción' })).toBeVisible()
  await page.getByRole('button', { name: 'Detener reproducción' }).click()
  const progress = page.getByTestId('lite-track-A-progress')
  const phase = await progress.getAttribute('stroke-dasharray')
  await page.waitForTimeout(150)
  await expect(progress).toHaveAttribute('stroke-dasharray', phase)
  await page.getByRole('button', { name: 'Reiniciar ciclo' }).click()
  await expect(page.getByRole('button', { name: 'Reproducir', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reproducir', exact: true }).click()
  await page.getByRole('button', { name: 'Reiniciar ciclo' }).click()
  await expect(page.getByRole('button', { name: 'Detener reproducción' })).toBeVisible()
  await selectPreset(page, '')
  await page.getByLabel('Numerador compás A', { exact: true }).fill('11')
  await page.getByRole('spinbutton', { name: 'Valor numérico BPM' }).fill('160')
  await page.getByRole('button', { name: 'Detener reproducción' }).click()
  await expect(page.getByRole('button', { name: 'Reproducir', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Reproducir', exact: true }).dblclick()
  await expect(page.getByRole('button', { name: 'Reproducir', exact: true })).toBeVisible()
})

test('two levels, explicit grouping accents and presets independent from every mode', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('navigation', { name: 'Niveles musicales' }).getByRole('button')).toHaveCount(2)
  await page.getByText('Agrupaciones (opcional)', { exact: true }).click()
  const cells = page.getByRole('group', { name: 'Secuenciador pista A' }).getByRole('button')
  await cells.nth(3).click()
  await page.getByRole('button', { name: 'Aplicar acentos a los grupos' }).click()
  expect(await cells.evaluateAll(items => items.map(item => Number(item.dataset.accent)))).toEqual([2,0,1,2,1,0,0])
  await page.getByRole('button', { name: 'Nivel 2 — Dos ritmos' }).click()
  for (const name of ['Polirritmia —', 'Polimetría —', 'Morph —', 'Clave —']) {
    const mode = page.getByRole('button', { name: new RegExp('^' + name) })
    await mode.click()
    await expect(mode).toHaveAttribute('aria-pressed', 'true')
    const b = page.getByRole('group', { name: 'Secuenciador pista B' }).getByRole('button')
    // Clave loads B in an effect. Capture its pattern after that transition,
    // rather than racing the previous mode's five-step grid on fast runners.
    if (name === 'Clave —') await expect(b).toHaveCount(16)
    const before = await b.evaluateAll(items => items.map(item => item.dataset.accent))
    await selectPreset(page, 'marcato')
    await expect(mode).toHaveAttribute('aria-pressed', 'true')
    await expect.poll(() => b.evaluateAll(items => items.map(item => item.dataset.accent))).toEqual(before)
  }
})

